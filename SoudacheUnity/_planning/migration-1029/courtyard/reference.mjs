import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const directory = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(directory, '../../../../搜打撤/game/src/hub/courtyard-vendor/KoiPond.js');
let code = fs.readFileSync(source, 'utf8').replace(/^import .*;\r?\n/m, '').replace('export function createKoiPond', 'function createKoiPond');
const marker = 'return {\n    resize';
code = code.replaceAll('\r\n', '\n');
if (!code.includes(marker)) throw new Error('Source snapshot instrumentation point changed');
code = code.replace(marker, 'return {\n    snapshot() { return {fish:kois.map(f=>({...f})),food:foods.length,ripples:ripples.length,found:found.size,eaten,time}; },\n    resize');
const create = new Function('Random', code + '\nreturn createKoiPond;')({});
let state = 1029;
const random = () => { state = (Math.imul(state, 1664525) + 1013904223) >>> 0; return state / 4294967296; };
const context = new Proxy({}, { get: () => () => {} });
const pond = create({width:1000,height:600,getContext:()=>context}, {random});
const stages = [];
pond.resize(1200, 700);
for(let i=0;i<100;i++) pond.render(.016);
stages.push(pond.snapshot());
let fish = stages[0].fish[0]; pond.pointer(fish.x,fish.y); pond.tap(fish.x,fish.y); pond.render(.016);
stages.push(pond.snapshot());
for(let i=0;i<40;i++)pond.tap(500,300);
pond.render(.05,false); stages.push(pond.snapshot());
fs.writeFileSync(path.join(directory,'reference.json'),JSON.stringify(stages,null,2));
console.log('Generated direct current KoiPond.js reference: 3 stages, 9 fish each');
