import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,'../../..');
const events=JSON.parse(fs.readFileSync(path.join(here,'current-events.json'),'utf8'));
const data=value=>value==null?'null':Array.isArray(value)?'new object[] { '+value.map(data).join(', ')+' }'
  :typeof value==='object'?'RuleValue.Obj('+Object.entries(value).flatMap(([k,v])=>[JSON.stringify(k),data(v)]).join(', ')+')'
  :JSON.stringify(value);
const output='// Generated by _planning/migration-1029/battle/export-events.mjs and generate-events.mjs from current eventChoiceSpec.\nnamespace Sdt.Core { public static class EventDatabase {\n'
  +' public static readonly RuleValue[] All = {\n'+events.map(event=>'  '+data(event)+',').join('\n')+'\n };\n'
  +' public static RuleValue Find(string id) => System.Array.Find(All, entry => entry.Text("id") == id);\n} }\n';
const target=path.join(root,'Assets/Scripts/Sdt.Core/Data/EventDatabase.cs');
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8'),output);else fs.writeFileSync(target,output);
console.log(JSON.stringify({events:events.length,choices:events.reduce((n,e)=>n+e.layers[0].length,0),generated:target}));
