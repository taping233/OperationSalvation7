const attack = amount => amount === 0 ? '造成等同于你的攻击力的攻击伤害'
  : `造成（你的攻击力 ${amount > 0 ? '+' : '-'} ${Math.abs(amount)}）点攻击伤害`;
const changes = cards.flatMap(card => {
  let text = textById[card.id];
  if (text === undefined && card.type !== '生物') {
    text = String(card.desc || '').replace(/^攻[（(]([+-]?\d+)[）)]/, (_, n) => attack(+n));
    text = text.replace(/(\d+)\s*(张|点|层|回合|次|名|瓶|个|费)/g, '$1 $2').replace(/[。；;\s]+$/, '') + '。';
    text = text.replace(/获得 (\d+) 点护甲/g, '你获得 $1 点护甲').replace(/回复 (\d+) 点生命/g, '你回复 $1 点生命');
  }
  return text && text !== card.desc ? [{ id: card.id, name: card.name, source: card.desc, text }] : [];
});
