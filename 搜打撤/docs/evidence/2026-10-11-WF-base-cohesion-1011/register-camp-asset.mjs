import fs from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
const root = process.cwd();
const evidence = 'docs/evidence/2026-10-11-WF-base-cohesion-1011';
const receipt = JSON.parse(fs.readFileSync(path.join(root, evidence, 'camp-runtime-receipt.json'), 'utf8'));
const manifestPath = path.join(root, 'game/assets/asset-manifest.json');
const raw = fs.readFileSync(manifestPath, 'utf8');
const manifest = JSON.parse(raw.replace(/^\uFEFF/, ''));
const assetPath = 'scenes/base-operations-v5.webp';
if (manifest.assets.some(item => item.path === assetPath)) throw new Error('Asset entry already exists; inspect before replacing.');
const runtime = fs.readFileSync(path.join(root, receipt.runtime.path));
if (runtime.length !== receipt.runtime.bytes || createHash('sha256').update(runtime).digest('hex') !== receipt.runtime.sha256) throw new Error('Runtime asset does not match receipt.');
const entry = {path:assetPath,ext:'webp',license:'项目自有（AI 生成）',bytes:runtime.length,sha256:receipt.runtime.sha256,source:`${evidence}/camp-runtime-receipt.json`};
const eol = raw.includes('\r\n') ? '\r\n' : '\n';
const anchor = /("assets"\s*:\s*\[)(\r?\n)/;
if (!anchor.test(raw)) throw new Error('Manifest array anchor missing.');
let updated = raw.replace(anchor, `$1${eol}${JSON.stringify(entry, null, 2).split('\n').map(line => '    '+line).join(eol)},${eol}`);
updated = updated.replace(/("count"\s*:\s*)\d+/, `$1${manifest.assets.length + 1}`);
const parsed = JSON.parse(updated.replace(/^\uFEFF/, ''));
if (parsed.assets.length !== manifest.assets.length+1 || parsed.count !== parsed.assets.length) throw new Error('Manifest count mismatch.');
if (JSON.stringify(parsed.assets.slice(1)) !== JSON.stringify(manifest.assets)) throw new Error('Unrelated manifest entries changed.');
if (fs.readFileSync(manifestPath, 'utf8') !== raw) throw new Error('Manifest changed during update. Retry from fresh input.');
fs.writeFileSync(manifestPath, updated);
console.log(JSON.stringify({entry,count:parsed.count,unrelatedEntriesPreserved:true}));
