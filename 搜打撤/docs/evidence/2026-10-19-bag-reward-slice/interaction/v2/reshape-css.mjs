function set(selector, props) {
  let found = false;
  css.walkRules(rule => {
    if (!rule.selectors.includes(selector)) return;
    found = true;
    for (const [prop, value] of Object.entries(props)) {
      rule.nodes.filter(node => node.type === 'decl' && node.prop === prop).forEach(node => node.remove());
      if (value !== null) rule.append({prop,value});
    }
  });
  if (!found) throw new Error(`Missing selector: ${selector}`);
}
