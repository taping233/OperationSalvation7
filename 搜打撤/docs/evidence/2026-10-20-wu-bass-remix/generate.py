import hashlib
import json
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'tools'))
import nai_gen
import nai_prompt_clean as style

SOURCE = Path('C:/Users/太平/Downloads/e8897f01f51cee6c83259072e91075ec236908.png')
PORTRAIT = ROOT / 'game/assets/portraits/full/wu.webp'
OUTPUT = ROOT.parent / '.tmp/nai/wu-bass-remix-20261020/candidate.png'
RECEIPT = Path(__file__).with_name('request.json')
assert not RECEIPT.exists() and not OUTPUT.exists()
with Image.open(SOURCE) as source:
    source.load()
    metadata = dict(source.info)

scene = ('1girl, solo, lying on her back on a worn rug, bent legs resting on the sofa, '
         'electric bass diagonally across her torso. Left fingers hold the fretboard; '
         'right fingers pluck above the pickups. Head closest to camera, upside-down face, '
         'half-lidded eyes, faint confident smile showing a small fang.')
composition = ('Wide horizontal composition, close floor-level perspective, enlarged bass headstock '
               'entering lower left foreground, silver ponytail spread across rug. Faded sofa, '
               'cushions, loose audio cables, mugs, practice sheets, small amplifier.')
lighting = ('Dim cyan overhead light, tiny violet amplifier indicator, muted teal-gray and dusty '
            'lavender palette, warm softly illuminated face and hands, intimate late-night lethargy.')
appearance = ('adult woman, fair skin, slender, blue eyes, silver-white long hair, high ponytail '
              'tied with blue ribbon bow, wispy bangs, black rose at her left temple, ordinary '
              'round black sunglasses perched on head. Oversized charcoal knit sweatshirt, '
              'loose lavender-gray pinstriped pajama trousers, thick ivory socks, fully clothed.')
characters = [dict(prompt=appearance, uc='pink hair, horns, tail, animal ears, goggles',
                   center=dict(x=.58, y=.55))]
prompt = style.build_asset_prompt(scene, composition_layer=composition, light_material_layer=lighting)
uc = style.build_uc('horns, reptile tail, animal ears, sword, sword harness, standing, white background')
request = nai_gen.build_payload(prompt, uc, seed=1859463027,
                                model='nai-diffusion-5-full', char_prompts=characters)
record = dict(status='prepared', recipe_version=style.RECIPE_VERSION, request=request,
              source_metadata=metadata,
              references=[dict(path=str(p), sha256=hashlib.sha256(p.read_bytes()).hexdigest(),
                               uploaded=False, role=role)
                          for p, role in [(SOURCE, 'composition, action, setting and light; embedded prompt'),
                                          (PORTRAIT, 'current Wu identity')]],
              retained='supine upside-down pose, sofa legs, bass and hand contacts, floor-level diagonal, room and light',
              replaced='Yvonne identity, pink/turquoise hair, horns, tail; current Wu identity and our artist chain',
              redesigned='charcoal knit sweatshirt, lavender-gray pinstriped lounge trousers and ivory socks; no sword',
              output=str(OUTPUT.relative_to(ROOT.parent)), acquisition='generated by nai_gen/nai_guard')
def save():
    RECEIPT.write_text(json.dumps(record, ensure_ascii=False, indent=2), encoding='utf-8')
save()
try:
    path, seed = nai_gen.generate_image(prompt, uc, seed=request['parameters']['seed'],
                                       model=request['model'], out=OUTPUT, char_prompts=characters)
except BaseException as error:
    record.update(status='failed', error_type=type(error).__name__, error=str(error))
    save()
    raise
record.update(status='generated', seed=seed, sha256=hashlib.sha256(Path(path).read_bytes()).hexdigest(),
              size_bytes=Path(path).stat().st_size)
save()
