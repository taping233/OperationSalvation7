import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
const directory = 'docs/evidence/2026-10-19-unused-cleanup';
const parse = file => JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
const plan = parse(directory + '/deletion-plan.json');
const receipt = parse(directory + '/deletion-receipt.json');
if (receipt.count !== 203 || plan.files.some(f => fs.existsSync(f.path))) throw Error('Approved deletion incomplete');
const expected = new Set(plan.files.map(f => path.resolve(f.path)));
if (receipt.paths.some(p => !expected.has(p)) || expected.size !== receipt.paths.length) throw Error('Deletion receipt scope differs');
receipt.approval = '老板在本聊天明确“执行”；203项路径与SHA256沿用deletion-plan.json';
receipt.planSha256 = createHash('sha256').update(fs.readFileSync(directory + '/deletion-plan.json')).digest('hex');
receipt.files = plan.files;
delete receipt.paths;
const beforeBytes = fs.readFileSync(directory + '/manifest-before.json');
const manifestFile = 'game/assets/asset-manifest.json';
if (!fs.readFileSync(manifestFile).equals(beforeBytes)) throw Error('Manifest changed concurrently');
const manifest = parse(manifestFile);
const retired = new Set(plan.files.filter(f => f.path.startsWith('game/assets/')).map(f => f.path.slice('game/assets/'.length)));
const kept = manifest.assets.filter(e => !retired.has(e.path));
receipt.removedManifestEntries = manifest.assets.filter(e => retired.has(e.path));
manifest.assets = kept;
manifest.count = kept.length;
fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
receipt.unrelatedManifestEntriesPreserved = kept.length;
fs.writeFileSync(directory + '/deletion-receipt.json', JSON.stringify(receipt, null, 2) + '\n');
console.log(JSON.stringify({deletedFiles: receipt.count, removedManifestEntries: receipt.removedManifestEntries.length, unrelatedManifestEntriesPreserved: kept.length}));
