function directoryEntries(root, file) {
  if (!existsSync(path.join(root, file))) return [];
  return readdirSync(path.join(root, file), { withFileTypes: true }).filter(entry => !entry.isSymbolicLink());
}

/** Mirrors index-validation's bounded read contract; links are existence checks, not text reads. */
export function documentationInputs(root, { archiveIndexes = [] } = {}) {
  const files = new Set(), existence = new Set(), inventories = [];
  const add = file => { if (existsSync(path.join(root, file)) && statSync(path.join(root, file)).isFile()) files.add(file); else existence.add(file); };
  const current = new Set();
  function currentDirectory(directory, recursive) {
    inventories.push({ directory, kind: 'current-documents', recursive });
    for (const entry of directoryEntries(root, directory)) {
      if (/^(?:archive|evidence|previews|modules)$/.test(entry.name)) continue;
      const file = path.posix.join(directory, entry.name);
      if (recursive && entry.isDirectory()) currentDirectory(file, true);
      else if (entry.isFile() && entry.name.endsWith('.md')) current.add(file);
    }
  }
  currentDirectory('docs', false); currentDirectory('docs/production', true);
  for (const file of ['README.md', 'AGENTS.md', '../AGENTS.md']) {
    if (existsSync(path.join(root, file))) current.add(file); else existence.add(file);
  }
  for (const file of archiveIndexes) { current.add(file); add(file); }
  inventories.push({ directory: 'docs/archive', kind: 'workflow-batches' });
  for (const entry of directoryEntries(root, 'docs/archive')) {
    if (!entry.isDirectory() || !/^(?:lean-)?workflow-/.test(entry.name)) continue;
    for (const name of ['manifest.json', 'source-manifest.json']) {
      const file = `docs/archive/${entry.name}/${name}`;
      add(file);
      if (!files.has(file)) continue;
      const manifest = JSON.parse(readFileSync(path.join(root, file), 'utf8'));
      if (!Array.isArray(manifest.items)) throw new Error('档案输入契约 items 不可解析：' + file);
      for (const item of manifest.items) for (const key of ['target', 'replacedBy']) {
        const relative = path.relative(root, path.resolve(root, item[key])).replaceAll('\\', '/');
        if (relative === '..' || relative.startsWith('../') || path.isAbsolute(relative)) throw new Error('档案输入越界：' + file);
        if (key === 'target') add(relative); else existence.add(relative);
      }
    }
  }
  for (const file of current) {
    add(file);
    const text = readFileSync(path.join(root, file), 'utf8');
    for (const match of text.matchAll(/!?\[[^\]]*\]\(\s*(?:<([^>]+)>|([^\s)]+))/g)) {
      const link = match[1] ?? match[2];
      if (/^(?:[a-z][a-z\d+.-]*:|#|\/\/|\/)/i.test(link)) continue;
      const target = link.split('#')[0].split('?')[0];
      if (!target) continue;
      existence.add(path.relative(root, path.resolve(root, path.dirname(file), decodeURIComponent(target))).replaceAll('\\', '/'));
    }
  }
  add('game/src/README.md');
  inventories.push({ directory: 'game/src', kind: 'source-domains' });
  return { files: [...files].sort(), existence: [...existence].sort(), inventories };
}

export function inputInventory(root, descriptor) {
  return directoryEntries(root, descriptor.directory).filter(entry => descriptor.kind === 'source-domains'
    ? entry.isDirectory() && entry.name !== 'generated' : descriptor.kind === 'workflow-batches'
      ? entry.isDirectory() && /^(?:lean-)?workflow-/.test(entry.name)
      : entry.isFile() && entry.name.endsWith('.md') || descriptor.recursive && entry.isDirectory() && !/^(?:archive|evidence|previews|modules)$/.test(entry.name))
    .map(entry => ({ name: entry.name, directory: entry.isDirectory() })).sort((a, b) => a.name.localeCompare(b.name));
}

// Static imports + explicit root contracts. Unknown dynamic imports or I/O fail closed.
export function dependencyScope(root, inputs) {
  const roots = [...new Set(inputs.map(file => file.replaceAll('\\', '/').replace(/^搜打撤\//, '')))];
  if (roots.length > 1) {
    const selections = roots.map(file => dependencyScope(root, [file]));
    const opaque = selections.find(selection => selection.mode !== 'targeted');
    if (opaque) return { mode: 'project', roots, files: [], reason: opaque.reason };
    const uniqueObjects = entries => [...new Map(entries.map(entry => [JSON.stringify(entry), entry])).values()];
    return { mode: 'targeted', roots, files: [...new Set(selections.flatMap(selection => selection.files))].sort(),
      existence: [...new Set(selections.flatMap(selection => selection.existence ?? []))].sort(),
      inventories: uniqueObjects(selections.flatMap(selection => selection.inventories ?? [])),
      contracts: uniqueObjects(selections.flatMap(selection => selection.contracts ?? [])),
      reason: '逐根独立证明输入范围；未知根不能借其他测试的fixture契约豁免' };
  }
  const files = new Set(), queue = [...roots], contracts = roots.map(file => INPUT_CONTRACTS.get(file)).filter(Boolean);
  const allowedIo = new Set(contracts.flatMap(contract => contract.io)), fixtureTests = new Set(roots.filter(file => INPUT_CONTRACTS.get(file)?.kind === 'fixture'));
  let external = { files: [], existence: [], inventories: [] };
  try {
    if (contracts.length && existsSync(path.join(root, 'scripts/workflow-dependencies.mjs'))) files.add('scripts/workflow-dependencies.mjs');
    if (contracts.some(contract => contract.kind === 'documentation')) {
      external = documentationInputs(root, { archiveIndexes: roots.includes('tests/docs-consistency.test.js')
        ? ['docs/archive/workflow-2026-09-30/README.md', 'docs/archive/workflow-routing-2026-09-30/README.md', 'docs/archive/workflow-completion-2026-09-30/README.md'] : [] });
      // The repository AGENTS is explicitly declared by docs:check, not a general import escape.
      for (const file of external.files) files.add(file);
    }
    while (queue.length) {
      const file = path.relative(root, path.resolve(root, queue.shift())).replaceAll('\\', '/');
      if (file === '..' || file.startsWith('../') || path.isAbsolute(file)) throw new Error('依赖越出项目');
      if (files.has(file)) continue;
      const absolute = path.join(root, file);
      if (!existsSync(absolute) || !statSync(absolute).isFile()) throw new Error('依赖文件不可达：' + file);
      files.add(file);
      if (!/\.(?:js|mjs|cjs)$/.test(file)) continue;
      const source = readFileSync(absolute, 'utf8');
      const imports = importsIn(source);
      if (!allowedIo.has(file) && (imports.some(item => /^(?:node:)?(?:fs(?:\/promises)?|child_process)$/.test(item.specifier))
        || /\b(?:readFileSync|readFile|readdirSync|readdir)\s*\(/.test(source))) throw new Error('动态进程/文件输入需完整范围：' + file);
      for (const { specifier } of imports) {
        if (!specifier.startsWith('.')) continue;
        queue.push(path.posix.normalize(path.posix.join(path.posix.dirname(file), specifier.split(/[?#]/)[0])));
      }
      // Explicit black-box inputs belong to tests; do not execute every command literal in a library.
      if (file.startsWith('tests/') && !fixtureTests.has(file)) for (const match of source.matchAll(/["'`]((?:game|scripts|tests|docs)\/[^"'`\s$]+\.(?:js|mjs|json|css|html|md))["'`]/g)) {
        if (existsSync(path.join(root, match[1]))) queue.push(match[1]);
      }
    }
    return { mode: 'targeted', roots, files: [...files].sort(), existence: external.existence, inventories: external.inventories,
      contracts: contracts.map(contract => ({ kind: contract.kind, reason: contract.reason })),
      reason: '静态依赖闭包与显式测试/命令输入契约；fixture生成的数据不锁当前项目' };
  } catch (error) {
    return { mode: 'project', roots, files: [], reason: '无法证明完整定向输入，保守扩大：' + error.message };
  }
}
