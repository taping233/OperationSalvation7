/* ============================================================
 * 离线烘焙卡面缩略图（卡牌库网格 / 悬停预览用）
 *
 * 用法（在 搜打撤/ 目录下）：
 *   npx electron game/tools/bake-card-thumbs.cjs
 *
 * 卡面原图宽 896~1792，而卡牌库的插画区被 CSS 钉死在 ≤215×165 CSS px
 * （expedition-library.css 的 .hs-card.lib .hsc-art 规则），等于 4~17 倍过采样：
 * 白花解码时间，245 张卡面解码后要占数百 MB，滚动时来回驱逐重解码。
 * 本脚本把 cardIcon 可能用到的三族图（cards/**、scenes/**、portraits/enemies/**）
 * 等比缩到宽 ≤ MAX_W（覆盖 dpr2 下的 215 CSS px），按同相对路径写入 assets/thumbs/。
 * 运行时 art.js 只在低倍率场景（库网格/悬停预览）换用 thumbs/ 路径，
 * 放大看卡面（#cardZoom）与战斗/立绘仍走原图。
 *
 * 同时写出 game/src/generated/thumb-manifest.js（vite.config 构建期会重写同一份），
 * art.js 靠它判断某张图有没有缩略图，缺了直接回退原图（不会 404）。
 * 素材更新后重跑一次即可；源图宽 ≤ MAX_W 的根目录外小图跳过不产出。
 * ============================================================ */
const { app, BrowserWindow } = require('electron');
const fs = require('fs');
const path = require('path');

const GAME = path.join(__dirname, '..');                 // game/
const ASSETS = path.join(GAME, 'assets');
const OUT = path.join(ASSETS, 'thumbs');
const MANIFEST = path.join(GAME, 'src', 'generated', 'thumb-manifest.js');
const SRC_DIRS = ['cards', 'scenes', path.join('portraits', 'enemies')];
const IMAGE_EXT_RE = /\.(webp|png|jpe?g)$/i;
const MAX_W = 448;    // 448 = 215 CSS px × dpr2 出头，卡面再大也超不过 CSS 的 max-width
const QUALITY = 0.82;

function walk(dir, prefix, out) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isDirectory()) walk(path.join(dir, e.name), rel, out);
    else if (IMAGE_EXT_RE.test(e.name)) out.push(rel);
  }
  return out;
}

// Canvas always emits WebP bytes, so raster sources with other extensions must
// also use .webp for the thumbnail output path.
function thumbRel(rel) {
  return rel.replace(/\.(?:png|jpe?g)$/i, '.webp');
}

// 在渲染进程里跑的单文件处理：返回 { url, w, h }、{ skip:true }（源图已够小）或 null
// 注意：本函数源码会被内嵌进渲染进程执行，不能引用本文件作用域的变量（一律参数传入）
// 尺寸判定放在这里而非主进程的 nativeImage：nativeImage 读不了 webp（getSize 返回 0），
// 而本项目卡面几乎全是 webp，放在主进程会把它们全部误判成「已够小」而跳过。canvas 能解码。
const processOne = (dataUrl, MAX_W, QUALITY) => new Promise((resolve) => {
  const img = new Image();
  img.onload = () => {
    try {
      const W0 = img.naturalWidth, H0 = img.naturalHeight;
      if (W0 <= MAX_W) return resolve({ skip: true });
      const W = Math.max(1, Math.round(W0 * Math.min(1, MAX_W / W0)));
      const H = Math.max(1, Math.round(H0 * (W / W0)));
      const canvas = document.createElement('canvas');
      canvas.width = W; canvas.height = H;
      const ctx = canvas.getContext('2d');
      ctx.imageSmoothingEnabled = true;
      ctx.imageSmoothingQuality = 'high';
      ctx.drawImage(img, 0, 0, W, H);
      resolve({ url: canvas.toDataURL('image/webp', QUALITY), w: W, h: H });
    } catch (e) { resolve(null); }
  };
  img.onerror = () => resolve(null);
  img.src = dataUrl;
});

const mimeOf = (f) => (/\.png$/i.test(f) ? 'image/png' : /\.jpe?g$/i.test(f) ? 'image/jpeg' : 'image/webp');

function writeManifest(list) {
  fs.mkdirSync(path.dirname(MANIFEST), { recursive: true });
  fs.writeFileSync(
    MANIFEST,
    `// AUTO-GENERATED by game/tools/bake-card-thumbs.cjs + vite.config.js — 每次构建重新生成，勿手改。\n`
    + `// 卡面缩略图清单：assets/thumbs/ 下全部图片（相对 thumbs/ 的 POSIX 路径）。\n`
    + `// 与源图同相对路径；art.js 命中清单时低倍率场景换用缩略图，否则回退原图。\n`
    + `export default ${JSON.stringify(list, null, 2)};\n`,
  );
}

app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, webPreferences: { nodeIntegration: true, contextIsolation: false } });
  await win.loadURL('about:blank');

  const produced = [];
  let baked = 0, fresh = 0, small = 0, failed = 0;

  for (const dir of SRC_DIRS) {
    const srcRoot = path.join(ASSETS, dir);
    if (!fs.existsSync(srcRoot)) continue;
    for (const rel of walk(srcRoot, dir, [])) {
      const src = path.join(ASSETS, rel);
      const out = path.join(OUT, thumbRel(rel));
      if (fs.existsSync(out) && fs.statSync(out).mtimeMs >= fs.statSync(src).mtimeMs) {
        produced.push(rel.replace(/\\/g, '/')); fresh++; continue;
      }
      const b64 = fs.readFileSync(src).toString('base64');
      const res = await win.webContents.executeJavaScript(
        `(${processOne.toString()})('data:${mimeOf(rel)};base64,${b64}', ${MAX_W}, ${QUALITY})`, true);
      if (res && res.skip) { small++; continue; }
      if (!res || !res.url) { console.log(`烘焙失败（保留原图）: ${rel}`); failed++; continue; }
      fs.mkdirSync(path.dirname(out), { recursive: true });
      fs.writeFileSync(out, Buffer.from(res.url.split(',')[1], 'base64'));
      produced.push(rel.replace(/\\/g, '/'));
      baked++;
      console.log(`OK ${rel} -> ${res.w}x${res.h}`);
    }
  }

  produced.sort();
  writeManifest(produced);
  console.log(`\n完成：新烘 ${baked} 张，已有 ${fresh} 张，源图已够小跳过 ${small} 张，失败 ${failed} 张`);
  console.log(`清单 ${produced.length} 条 -> ${path.relative(GAME, MANIFEST)}`);
  app.quit();
});
